"""Build sky.js: the naked-eye stars (magnitude 6.5 or brighter) as a backdrop at infinity.

Source: Star Explorer's stars.js (HYG v3, equatorial Cartesian, parsecs). Only each star's
direction, magnitude, and B-V color index are kept, with directions rotated into the ecliptic
J2000 frame the rest of the app uses. Sol is skipped. The output is a derivative of the HYG
Database and, like it, licensed CC BY-SA 4.0.

Run:  python3 tools/make_sky.py [path/to/stars.js]
"""
import datetime
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(os.path.dirname(ROOT), "uncharted", "starmap-real", "stars.js")
MAG_LIMIT = 6.5
OBLIQ = math.radians(23.4392811)   # J2000 obliquity of the ecliptic (IAU 2006)


def load_hyg(path):
    text = open(path).read()
    cols = json.loads(text.split("window.HYG_COLS=", 1)[1].split(";", 1)[0].replace("'", '"'))
    body = text.split("window.HYG_STARS=", 1)[1].strip()
    if body.endswith(";"):
        body = body[:-1]
    return cols, json.loads(body)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    cols, rows = load_hyg(src)
    ci = {c: i for i, c in enumerate(cols)}
    co, so = math.cos(OBLIQ), math.sin(OBLIQ)
    stars = []
    for r in rows:
        if r[ci["id"]] == 0 or r[ci["mag"]] > MAG_LIMIT:
            continue
        x, y, z = r[ci["x"]], r[ci["y"]], r[ci["z"]]
        d = math.sqrt(x * x + y * y + z * z)
        if d == 0:
            continue
        x, y, z = x / d, y / d, z / d
        ye, ze = co * y + so * z, -so * y + co * z     # equatorial -> ecliptic J2000
        bv = r[ci["ci"]] if r[ci["ci"]] not in ("", None) else 0.65
        stars.append((r[ci["mag"]], x, ye, ze, bv))
    stars.sort()   # brightest first
    flat = []
    for mag, x, y, z, bv in stars:
        flat.extend(("%.4f" % x, "%.4f" % y, "%.4f" % z, "%.2f" % mag, "%.2f" % bv))
    out = os.path.join(ROOT, "sky.js")
    with open(out, "w") as f:
        f.write("// sky.js: naked-eye stars (magnitude %.1f or brighter) for Solar System Explorer's backdrop. %d stars.\n" % (MAG_LIMIT, len(stars)))
        f.write("// Source: HYG Database v3 (David Nash / astronexus), via Star Explorer's stars.js. CC BY-SA 4.0:\n")
        f.write("// https://github.com/astronexus/HYG-Database. This file is a derivative and is likewise CC BY-SA 4.0.\n")
        f.write("// Per star: x, y, z (unit direction, ecliptic J2000, as seen from the Sun), magnitude, B-V color index.\n")
        f.write("// Generated by tools/make_sky.py on %s. Do not edit by hand.\n" % datetime.date.today().isoformat())
        f.write("window.SOLAR_SKY = [%s];\n" % ",".join(flat))
    print("%d stars (mag <= %.1f), brightest %.2f; wrote %s (%.0f KB)" % (len(stars), MAG_LIMIT, stars[0][0], out, os.path.getsize(out) / 1024))


if __name__ == "__main__":
    main()
